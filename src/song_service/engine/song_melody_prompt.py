def _line_len_text(section, groove) -> str:
    """「この区間の1行はどれだけの長さか」を文にする（**割り算はこちらでやる**）。

    設計の小節数 ÷ グルーヴの行数 が「1行の小節数」。ここを言葉（「1小節16文字」）だけで
    渡していたとき、**1行が2小節の区間でも16文字**が返り、区間が設計の半分になった
    （2026-09-09）。

    ★**長さの単位は、書かせる記法と同じものにする**（2026-09-20／21）。
      ABC へ移したとき、**尺だけ「小節」に直して、間隔の指示は「文字」のまま**だった。
      ABC に「文字」という単位は無い（`C2` は2文字ではなく **2単位**）ので、
      宙に浮いた指示になっていた。`L:1/16` なので **1単位＝16分**＝旧「1文字」。
      **数字と帯は実測のまま**、呼び名だけを記法に合わせてある。
    """
    b = int(getattr(section, "bars", 0) or 0)
    g = next((x for x in getattr(groove, "sections", []) if x.kind == section.kind), None)
    ln = int(getattr(g, "lines", 0) or 0)
    if not b or not ln:
        return ""
    # 割り切れないときは行ごとに配る（8小節を3行なら 3+3+2）ので、そのまま並べて渡す
    xs = _line_slots({section.kind: g}, {section.kind: b}).get(section.kind) or []
    # ★★**「何文字あけるか」も、こちらで割って渡す**（2026-09-12）★★
    #
    #   プロンプトには「音節どうしの間隔は2文字（8分）を基本に・5文字以上は使わない」と
    #   **文字数で**書いてあったが、それは BPM75 を前提にした数字だった。
    #   速い曲では 2文字＝0.17秒しかないので、**モーラ数を2文字間隔で並べると
    #   行の 1/3 しか埋まらず、残りが1つの大きな穴になる**。
    #
    #   > 実際に起きたこと（2026-09-12『名前のない風になって』BPM175）:
    #   > 1行 32文字に6モーラで `--o-o-o-o-------|---------o-o----|`——
    #   > 4音を8分で詰めたあと **17文字（1.46秒）の空白**。行の中で息が切れ、
    #   > **ひと息 1.59秒**（帯 2.50〜6.50）になった。
    #   > **枠の文字数とモーラ数は渡していたのに、その割り算だけ渡していなかった。**
    _m = int(getattr(g, "moras_per_line", 0) or 0)
    # ★★**間隔は偶数で渡す**（2026-09-13・本人「7番がリズムに合ってる感じがしない」）★★
    #
    #   朝に「およそ 5 文字」と渡したら、旋律は **3文字間隔**で並べた。3 は奇数なので
    #   踏む位置が `&・e・拍頭・a` と毎回ずれ、**4割の音が `e`（拍の16分ぶん後ろ）**に
    #   落ちた。`e` は「拍から遅れて入る」位置で、引きずって聞こえる。
    #   気に入られた曲は `e` 0.9%・`a` 0.0%＝**8分の格子だけ**を使っていた
    #   （`test/song_quality_bench/grid_position.py`・n=4）。
    #   だから**偶数（2・4・6）だけを勧め、平均が奇数なら「4と6を混ぜる」**と渡す。
    #   奇数（3・5）は「詰めたい所だけ」に限る（プロンプト側に書いてある）。
    # ★★**「均等に広げる」をやめ、「塊＋本当の休み」で渡す**（2026-09-13 夕・RWC-P 実測）★★
    #   昼に「平均 5.3 文字なので 4 と 6 を混ぜて均等に」と渡したら、歌う小節の音節が
    #   **3.3/小節**（実曲 5〜6）、音節間隔 1.0拍（8分 0%）になり、本人「文字数が少なすぎる・間延び」。
    #   実曲（RWC-P 73曲）は**ひと息の中は 8分〜4分で詰めて歌い（歌っている割合 89〜96%）、
    #   ひと息のあいだに本当に休む**。総数は同じでも分布が違う。
    #   だから: 2文字（8分）を基本に 4文字を混ぜ、**行の前半〜中ほどに固めて、余りは行末にまとめる**。
    #   6文字以上は使わない（それは「休み」で表す）。奇数は引きずる（`e` を踏む）ので変わらず避ける。
    # ★★**言葉の運びは数字で受ける**（2026-09-16・`notes_per_beat` / `tail_rest`）★★
    #   それまで「塊＋行末の休み」だけを書いていたので、**もう片方が作れなかった**。
    #   参考曲（BPM204・作者配布の公式 MIDI）を測ると、**1拍ごとの音数が
    #   23.7 / 26.7 / 25.0 / 24.6% と完全に均等**で、**行末の空きは中央 0%**、
    #   **ひと息 中央 8.97秒・最長 19.1秒・1息 最多 119音**だった
    #   （うちの曲は 2拍目に 44.5%・ひと息 3.9秒・1息 10音）。
    #   **どちらが正しいかではなく、どちらの作風か**なので、グルーヴに宣言させて選ぶ。
    #   ★**数字から文にする**（2026-09-16）。`tail_rest`＝行末をどれだけ空けるか、
    #     `notes_per_beat`＝1拍に何個置くか。**名前ではなく数で渡す**ので、
    #     「少しだけ空ける」のような中間も書ける。
    _tail = groove_number(g, "tail_rest")                # 歌のある区間は数（null は検査が返す・2026-10-04 組N2。以前は既定 0.30・1.0）
    _npb = groove_number(g, "notes_per_beat")
    _upb = grid_per_bar()                                  # 1小節の単位数（拍子から・4/4=16 / 3/4=12）
    # ★**感じる拍で数える**（2026-09-30・出-5）。6/8 は付点4分×2拍なので「2つの拍」。以前は4分音符で数え「3つの拍」と伝えていた
    _heads = beat_heads(ctx.METER)                         # 拍の頭（16分の単位・1始まり）
    _bpb = len(_heads)                                     # 1小節の拍数（感じる拍）
    _beats = (xs[0] / _upb * _bpb) if xs else 0.0          # この行の拍数
    if xs and _m >= 2 and _tail < 0.10:
        _per = _m / max(1.0, _beats)                       # 1拍あたり何個になるか
        _gap = (f"——**音節を{_bpb}つの拍に均して置いてください**（**どの拍にも "
                f"{max(1, round(_per))}〜{max(1, round(_per)) + 1}個**）。"
                f"**2単位（8分）間隔を基本に、行の頭から最後まで切れ目なく**並べ、"
                f"**行末に休みを作らないでください**（次の行へそのまま流します）。"
                f"★**{_bpb}拍目（各小節の{_heads[-1]}〜{_upb}単位目）が空きやすい**——1小節ずつ数えて確かめること。"
                f"奇数（3・5）は引きずるので使わない")
    elif xs and _m >= 2:
        _sung = int(round(xs[0] * (1.0 - _tail)))          # 音節が占める単位数＝行末を空けた残り
        _gap = (f"——**音節は 2単位（8分）を基本に 4単位（4分）を混ぜて、行の前半〜中ほどに"
                f"固めてください**。{_m}モーラなら音節の並びはおよそ {_sung} 単位ぶん、"
                f"残り {max(0, xs[0] - _sung)} 単位は**行末にまとめて空ける**（そこで伸ばす・息を継ぐ）。"
                f"**行全体に均等に広げないでください**——歌う小節の音節が実曲の半分になり、間延びします。"
                f"6単位以上の間隔と奇数（3・5）は使わない")
    else:
        _gap = ""
    if xs and _m >= 2:
        _gap = (f"【1拍に {_npb:.2f}個・行末の空き {_tail:.0%}】{_gap}")
    # ★**尺は「小節数」で言う**（2026-09-20 の記法移行）。それまで「onsets は 32 文字」と
    #   書いていたが、ABC へ移したことで **`onsets` が何かの説明がプロンプトから消え**、
    #   **宙に浮いた指示**になっていた。実際に1回通したら、同じ区間なのに行が
    #   3小節・3小節・2小節とばらつき（型の再出現 0.716／帯 0.86〜0.98）、
    #   **区間の尺が設計から外れた**。**長さの単位は、書かせる記法と同じものにする。**
    if len(set(xs)) == 1:
        per = xs[0] // grid_per_bar()
        return (f"　★**{ln}行・1行 {per}小節ちょうど**"
                f"（ABC で `|` を {per - 1 if per > 1 else 0} 本はさみ、各小節{_upb}単位）{_gap}　")
    return ("　★**" + f"{ln}行・1行の小節数は行ごとに "
            + "／".join(str(x // grid_per_bar()) for x in xs) + "（順に）**　")


# ★**拍子の伝え方は `song_design.meter_text` の1か所**（2026-09-30・出-5）。旋律（ここ・`song_melody_step`）・グルーヴ
#   （`song_outline`）・声部の表（`song_table`）が同じ文を使う。以前はここに旋律用、グルーヴに別の文があり、6/8 を
#   「3拍・拍の頭は 1・5・9 単位目」（3/4 の割り方）で伝えていた。`meter_text` の名前はここからも引ける（旧い読み手のため）


def melody_prompt(theme, design, chords, groove, sung, ch_map, top: int, floor: int | None = None) -> str:
    """**旋律工程へ渡す依頼文**を組み立てる（2026-09-09 に関数へ出した）。

    ここを `_compose_once` の中に書いていたため、**どのテストも通っていなかった**——
    実際に文字列の連結を書き間違え（`+` が二重）、本番を4工程ぶん走らせたあと
    `TypeError` で落ちた。`py_undefined_check` も pytest も**組み立てを一度も実行していなかった**。
    """
    return (
        ctx.brief(theme, design, chords)
        + f"\n\n仮の曲名『{theme.working_title}』BPM{design.bpm} 種類={theme.genre}\n"
        + meter_text(design.time_signature) + "\n"
        # ★**音域は数字で渡す**（2026-09-09）。`low / mid / high` の語だけでは効かず、
        #   「verse は low」と決めた曲で**曲全体の中央が D5(74)・最高音 E6(88)**になった
        #   （本人に「テンポに対して声が高かった」と言われた）。
        #   設計が決めた `top_note` を上限として、区間ごとの中心も**音名で**示す。
        # ★**高さは国際式の音名に ABC の書き方を添える**（2026-10-01・本人「楽譜（国際式の音名）に寄せる」）。以前は
        #   `81（ラ5）` のように MIDI 番号と階名で、旋律が書く ABC とどちらも違う物差しだった
        # ★**1行が何文字かを、区間ごとに数字で出す**（2026-09-09）。
        #   「1小節16文字」とだけ書いていたので、**1行が2小節の区間でも16文字**が返り、
        #   区間が設計の半分の長さになった（8小節→5小節・密度が倍）。
        #   小節数と行数から**割り算はこちらでやって**、答えだけ渡す。
        # ★**コードは伴奏・彩りと同じ形 `1:Am | 2:F G`**（2026-10-02・`song_arrange.chord_row`・仕様書 §16）。以前は小節を `-` で
        #   つないでいた（`Am-F-C-G`）。`-` はコード名の中で ♭（`C7-9`）にも使うので、小節の区切りと見分けにくかった
        + "\n".join(f"■{s.kind}（{s.bars}小節・{_center_text(s.pitch_center, top)}）"
                    + _line_len_text(s, groove)
                    + f"コード: {chord_row(ch_map.get(s.kind, []))}" for s in sung)
        + "\n（コードは `小節:コード` を ` | ` で区切る。小節はその区間の中で1から数える。1小節に `Am F` のように並んでいれば、"
          "並べた数で小節を均等に分けて替わる。コード名は旋律と同じ C メジャー／A マイナー基準）"
        + f"\n★**この曲の最高音は {pitch_with_abc(top)} です。ここを超えないでください。**"
          f"サビでそこまで上げ、他の区間はもっと低く保ちます。"
        + (f"\n★**最低音は {pitch_with_abc(floor)} です。これより低く書かないでください。**" if floor else "")
        # ★★**シンコペーションは、曲ごとの依頼文にも書く**（2026-09-11）★★
        #
        #   同じ内容が `song_melody.md` に**もっと詳しく**書いてある（「3分の2〜9割は
        #   拍の頭以外」「拍頭は1行に1〜2個まで」＋使える枠の見本）。それでも
        #   **LLM が書いた枠の拍頭率は 0.520**（実測 p20〜p80 は 0.07〜0.43）。
        #   同じ内容を**短いプロンプト**で渡した実験では **0.194** だった。
        #   **200行超のプロンプトの中では埋もれる**——情報は届いていて、スキーマも許していて、
        #   回避でもない。**ただ読まれていない**という4つ目の型。
        # ★★**S/M/C で「行の終わりをどこに置くか」を変えさせる**（2026-09-11）★★
        #
        #   行が枠をぴったり埋めるようにしたので、**伸ばし＋休み＝枠の残り**が一定になった。
        #   すると**伸ばしを長くすると休みが必ず短くなり**、
        #   「大きく区切るところほど長く伸ばし、長く休む」という関係が**構造的に作れない**
        #   ——実測で**必然性 −0.530**・**ばらつき 0.083**（帯 0.05〜1.00／0.38〜0.93）。
        #   残りの量そのものを行ごとに変えるには、**最後の音を置く場所**を変えてもらうしかない。
        + "\n★**行の終わりは、区切りの記号で置き場所を変えてください**:\n"
          "  **S**（文が終わる）… 最後の音を**1小節ぶん早めに置く**（あとを大きく空ける）\n"
          "  **M**（息を入れる）… 半小節ぶん早めに置く\n"
          "  **C**（そのまま続く）… **終わり近くまで音を置く**（空けない）\n"
          "  空けたぶんが「伸ばし」と「休み」になります。**空けなければ、伸ばせません。**\n"
        + "\n★**この2つを両立させてください**（片方だけだともう片方が崩れます）:\n"
          "  ① **拍の頭から始めすぎない**——拍の頭（4/4 なら1・5・9・13単位目。この曲の数は上の「この曲の拍子」）に"
          "音の頭を置くのは**1行に1〜2個**（実測でヒット曲は 1〜3割）\n"
          "  ② **同じ区間の行は、前半をほぼ同じ型にする**（実測で4音の型の 9割が再び現れる）\n"
          # ★2026-09-30（記-5）: ここだけ、やめた枠の記法（`-` と `o` で16文字）の例が残っていた。ABC で書き直した
          "    ○（4/4 の例）1行目 `z2 E2 D4 C2 D4 E2` ／ 2行目 `z2 E2 D4 C2 E6`"
          "（**頭は同じ・終わりだけ違う**・音の頭が拍の頭に来るのは 5・9 単位目の2個）\n"
          "    × `C4 D4 E4 F4`（4個とも拍頭）／"
          "× `z16`（**小節を丸ごと空にしない**）"
        + groove_text(groove, sung)
        # ★**そのジャンルの実測を渡す**（2026-09-09）。以前は全ジャンル共通の帯だけを渡しており、
        #   しかも根拠が**中国のポップス**だった。日本語の歌には J-POP 100曲の実測を使う。
        + reference_text(theme.genre, design.bpm, getattr(design, "devices", None))
        + "\n\n**全体方針を旋律で実現してください。**目安から外れても、方針に沿うならそれが正解です。"
        + _MELODY_GUIDE.format(genre=ctx._GENRE_NAME[theme.genre]))


def _center_text(center: str, top: int) -> str:
    """区間の音域中心を**音名の範囲**（国際式・`F4〜A5`）で示す（`low` などの語だけでは効かなかった）。"""
    # 音域の狙いは型（`PitchCenter`）で閉じている（2026-09-30）。以前は選択肢に無い綴りを黙って mid にしていた
    lo = {"low": top - 12, "mid": top - 7, "high": top - 4}[center]
    # ★国際式の音名に ABC の書き方を添える（2026-10-01・仕様書 §16「旋律の依頼文の音域」。最高音・最低音と同じ物差し）
    a, b = max(58, lo - 5), lo + 3
    return f"音域 {_note_name(a)}〜{_note_name(b)}（ABC の `{abc_pitch(a)}`〜`{abc_pitch(b)}`）あたり"


def _grid_legend(ts: str) -> str:
    """グルーヴの8分の格子の位置の読み方（拍子ごと）。拍の頭は `song_design.beat_heads` から。"""
    from song_design import grid_slots
    n = grid_slots(ts)
    heads = {(h - 1) // 2 for h in beat_heads(ts)}         # 8分の格子の何番目（0始まり）が拍の頭か
    if len(heads) * 2 == n:                                # 4分音符の拍（4/4・3/4・2/4）: 1 & 2 & …
        marks, k = [], 0
        for i in range(n):
            if i in heads:
                k += 1
                marks.append(str(k))
            else:
                marks.append("&")
    else:                                                  # 付点4分の拍（6/8）: 8分を1から数える
        marks = [str(i + 1) for i in range(n)]
    on = "・".join(str(i + 1) for i in sorted(heads))
    on16 = "・".join(map(str, beat_heads(ts)))
    return (f"位置は `{' '.join(marks)}`（{ts}）——**{on} 番目が拍の頭**、ほかは拍の中（裏）です。"
            f"16分で書いた行（倍の文字数）なら、拍の頭は {on16} 番目。")


def groove_text(groove, sung: list) -> str:
    """グルーヴを**旋律を書く人に読める形**にする（2026-09-07 新設）。

    ★**グリッドをそのまま並べると「写し」が起きる**——実験で、ドラムの記号列を渡したら
    旋律が8分グリッドを真似て**音の密度 2.95・ひと息 1.8秒**まで詰まった。
    そこで**位置の意味**（どこが拍の頭で、どこが裏か）を言葉で添え、
    **土台であって写す対象ではない**ことを明示する。
    """
    if not groove:
        return ""
    gv = {g.kind: g for g in groove.sections}
    out = [f"\n\n【この曲のノリ】{groove.feel}",
           # ★凡例はグルーヴの工程が書いた記号に合わせる（2026-09-29）。以前は「X=強く x=弱く -=鳴らさない・8個」と
           #   ドラムタブ（o/x）ともベース（`-`＝伸ばす）とも違い、3/4 の曲でも8個と書いていた
           "1小節を8分音符で割った記号（4/4 なら8個・3/4 と 6/8 なら6個。倍の文字数なら16分）。"
           "ドラム: o=太鼓を叩く x=シンバル類 大文字=強く .=とても弱く -=休み／"
           "ベース: X x .=弾く（強さ） -=前の音を伸ばす _=そこで切る",
           # ★拍子ごとに出す（2026-09-30・出-5）。以前は 4/4 の `1 & 2 & 3 & 4 &` だけで、6/8 の曲にもそれを見せていた
           _grid_legend(ctx.METER),
           "★**これは土台であって、写す対象ではありません。**"
           "同じ刻みを歌でなぞると音が詰まり、歌になりません。",
           "**このノリの上で気持ちよく歌える線**を書いてください——"
           "裏から食い込む、白玉で伸ばす、休んで待つ、どれも土台があるから効きます。"]
    for s in sung:
        g = gv.get(s.kind)
        if not g:
            continue
        out.append(f"■{s.kind}（**{g.lines}行 × 1行 {g.moras_per_line}モーラ**）")
        for d in g.drums:
            out.append(f"   {d.inst:<18} {d.pattern}")   # 幅は GM の名前（最長 acoustic_bass_drum）に合わせる
        out.append(f"   {'bass':<18} {g.bass}")
        # ★**言葉の運びは数字**（2026-09-16）。1拍に何個・行末をどれだけ空けるか。
        _t = groove_number(g, "tail_rest")
        out.append(f"   {'密度':<9} 1拍に {groove_number(g, 'notes_per_beat'):.2f}個"
                   f" ／ 行末の空き {_t:.0%}   "
                   + ("（**どの拍にも均して置き、行末で休まず次へ流す**）" if _t < 0.10
                      else "（音節を行の前半〜中ほどに固め、余りを行末の休みにする）"))
        # ★**行ごとの区切りの強さ**（2026-09-09 新設）。ここが旋律と詞をつなぐ唯一の宣言。
        if g.breaks:
            # 区切りの記号は記法の型の読み手で1行1文字に（`song_design.BREAKS`。生の文字列を1字ずつ割らない）
            out.append(f"   {'区切り':<9} {' '.join(BREAKS.read(g.breaks))}   "
                       f"（S=文が終わる／M=息を入れる／C=そのまま続く）")
    if any(getattr(gv.get(s.kind), "breaks", "") for s in sung):
        # ★**順位で言う**（2026-09-09）。「S は長く」だけでは守られなかった——
        #   実測で、`MCMS` と宣言したのに**いちばん長く伸ばしたのは C の行**だった
        #   （必然性は +0.525 と高いのに、宣言とは食い違っていた）。
        #   **どの行がいちばん長いか**を、順位として言い切る。
        out.append("★**「区切り」の記号どおりに、末尾の長さを決めてください。**"
                   "\n  **必ずこの順にする**: **S の行 ＞ M の行 ＞ C の行**（末尾音の長さ）"
                   "\n  ・**S** … その区間で**いちばん長く伸ばす**。そのあと長めに休む"
                   "\n  ・**M** … 中くらい。息を入れるぶんだけ休む"
                   "\n  ・**C** … **いちばん短く切る**。休まずすぐ次の行へ続ける"
                   "\n  ※**C の行を S より長くしてはいけません。**"
                   "実際にそれが起きました（2026-09-09）——"
                   "「長く伸ばしたら長く休む」という辻褄は合っていたのに、"
                   "**伸ばす行が宣言と違って**いました。"
                   "\n  ※**行の順番で機械的に決めない**。上の記号どおりに置いてください。")
    out.append("★**行数とモーラ数はこの土台で決めたものです。**"
               "フレーズ数と1フレーズの音数を、これに合わせてください"
               "——同じ区間の行は**長さを揃える**と、型が戻ってきて聴き手が乗れます。")
    return "\n".join(out)


def reference_text(genre: str, bpm: float, devices: list[str] | None = None) -> str:
    """参照値を**旋律を書く人が使える形**にする（2026-09-09）。

    ★**7原則に沿って書く**（`docs/plan/song_expression_map.md` §2）——
    範囲をそのまま渡すと **LLM は中央値1点に集中する**（実測: 16フレーズ中12本が同じ値）。
    だから**個数・回数・種類数**に翻訳して渡し、割合や分位数は渡さない。
    """
    r = reference(genre)
    if not r:
        return ""
    spb = 60.0 / max(1.0, bpm)

    def mid(k: str) -> float:
        return float(r[k][1])

    lines = [f"\n\n【この種類の曲（{genre}）で実際にどう作られているか】"
             f"——{r.get('曲数', 0)}曲の実測。**守る目標ではなく、外れるなら理由がある、という目安**",
             f"・ひと息で歌う長さ … 中央 **{mid('ひと息の秒'):.1f}秒**"
             f"（{r['ひと息の秒'][0]:.1f}〜{r['ひと息の秒'][2]:.1f}秒）",
             f"・1音の長さ … 中央 **{mid('1音の秒') * 1000:.0f}ミリ秒**"
             f"＝この曲では **{mid('1音の秒') / spb:.2f}拍**",
             f"・1秒あたりの音数 … 中央 **{mid('音の密度'):.1f}音**",
             f"・句末の伸ばし … 中央 **{mid('伸ばしの秒'):.2f}秒**"
             f"＝この曲では **{mid('伸ばしの秒') / spb:.1f}拍**"]
    # ★個数・回数・**具体値**へ翻訳する（原則1〜4）。
    #   実測（2026-09-09・ヘッドレス）: 「3種類以上使う」とだけ書いた版は
    #   伸ばし 0.75秒・ばらつき 0.42 で**どちらも p20 未満**だった。
    #   **どの行をどれだけ伸ばすか**を具体値で割り当てると守られる（原則1＋原則2）。
    def _beats(sec: float) -> float:
        """秒 → この曲の拍（0.5拍刻みに丸める＝書ける値の集合にする）。"""
        return max(0.5, round(sec / spb * 2) / 2)

    lo_h, mid_h, hi_h = (_beats(r["伸ばしの秒"][i]) for i in range(3))
    lines += [
        "",
        "**書くときはこう決めてください**:",
        f"・ひと息は **{mid('ひと息の秒'):.1f}秒前後**——この曲なら"
        f" **1フレーズ {max(3, round(mid('ひと息の秒') * mid('音の密度')))}音前後**",
        # ★★**「長さを割り当てる」のをやめた**（2026-09-09・本人指示）★★
        #   「1行目1.5拍・2行目1拍…」と具体値を渡していたが、それは
        #   **構造と無関係にばらつきだけを作る指示**だった。実測で確かめたところ、
        #   ヒット曲の伸ばしは**周期的ではなく**、**そのあとの休みの長さと結びついている**
        #   （末尾音↔次の休み: J-POP +0.297・正だった曲 88%／中国 +0.382・97%）。
        #   つまり**「大きく区切るところほど長く伸ばす」という工夫**の結果だった。
        #   だから**工夫そのものを言う**。数値ではなく理由を渡せば、
        #   歌詞の切れ目と結びつけて判断できる。
        "・★**伸ばす長さは「そのあと、どれだけ休むか」で決める**——",
        "    **次に長く休む（文の終わり・区間の終わり）なら、その手前は長く伸ばす**",
        "    **すぐ次へ続ける（言葉が途中）なら、短く切る**",
        f"  この曲での目安: たっぷり保つとき **{hi_h:g}拍**／ふつう **{mid_h:g}拍**／"
        f"短く切るとき **{lo_h:g}拍**",
        "  ※**行の順番で機械的に決めない**。**切れ目の大きさで決める**"
        "（実測でも、伸ばしの長さに周期はありませんでした）",
        # ★**伸ばす音そのものの選び方**（2026-09-09）。本人の指摘:
        #   「伸ばす長さはランダムではなくて、**落ち着きがよいところに配置しないと**」
        #   実測（J-POP 100曲・35,588音）: いちばん長い音だけが
        #   **コード構成音である割合 69.8%**（短い音は 61.0%）と跳ね上がる。
        "・★**長く伸ばす音は「落ち着く音」に置く**——その瞬間の**コードの構成音**、"
        "できれば**根音か5度**にする。",
        "    長く伸ばした先が不安定な音だと、**伸ばすほど気持ち悪くなります**。",
        "    短い音は経過音でよい（実測でも、落ち着く音を選んでいるのは**伸ばす音だけ**でした）",
    ]
    # ★**工夫は「使う」と宣言されたものだけ渡す**（2026-09-09）。
    #   それまで全曲へ同じ指示を出しており、作風を選べなかった。
    #   使う工夫は設計（`Design.devices`）が構想から決める。
    # ★**書いた工夫は全部渡す**（2026-10-03 本人「あえてそういう曲を作る余地はあってもいい」）。
    #   2026-09-09〜10-03 は「1〜2個」と頼んでも3つ選ばれることがあったので先頭2つに黙って絞っていた
    #   （3つ目は設計の LLM にも点検役にも知らされずに消えた）。数は設計の LLM が `concept` に理由を書いて決める
    _dev = set(devices or [])
    if "食い" in _dev:
        lines.append("・★**食いを効かせる曲です**——**8小節に1〜2回**、"
                     "小節の最後の8分から出して次の小節へまたいでください（前のめり・推進力）")
    if "跳躍" in _dev:
        lines.append("・★**跳躍を効かせる曲です**——山になる場所で **4〜8度**跳び上げてください")
    if "同音反復" in _dev:
        lines.append("・★**同音反復を効かせる曲です**——立てたい言葉で同じ音を続けてください"
                     "（ただし4つ以上並べると棒読みになります）")
    return "\n".join(lines)
