#: 所見が無いときの文（`song_gate.judge` の【機械検査の所見】。この節があるとき）
NO_FINDINGS = "  （上の【この工程で機械が確かめたこと】の検査をして、所見は見つからなかった）"

_HEAD = "【この工程で機械が確かめたこと】（読み方: ①は確かめ直さなくてかまいません／②は判断の材料です／③に時間を使ってください）"
_GUARANTEE = ("① 形式の検査で保証済みのこと（見直さなくてかまいません）。守れていなければ、その工程に直させ、"
              "直らなければその工程で曲づくりを止めています。ここに届いた稿はこれを満たしています:")


def _ok(cond, form: str) -> bool:
    conds = (cond,) if isinstance(cond, str) else tuple(cond)
    for c in conds:
        if c.startswith("!"):
            if form == c[1:]:
                return False
        elif c in FORM_STEPS:
            if form != c:
                return False
        elif c not in FORM_STEPS[form]:
            return False
    return True


def items(rows: tuple[Item, ...], form: str) -> list[str]:
    """条件つきの項目から、その形で当てはまるものだけを取る。"""
    out = []
    for r in rows:
        if isinstance(r, str):
            out.append(r)
        elif _ok(r[1], form):
            out.append(r[0])
    return out


def _step_line(step: str, cover: bool = False) -> str:
    rows = list(FORM_CHECKS[step])
    if cover and step in COVER_FORM_NOTE:
        rows.append(COVER_FORM_NOTE[step])
    return f"  ・{step}: " + "・".join(rows)


def gate_key(gate: str, cover: bool) -> str:
    return f"カバー:{gate}" if cover else gate


def checks_text(gate: str, form: str = "song", *, cover: bool = False) -> str:
    """点検役 `gate` の依頼文に足す【この工程で機械が確かめたこと】（表に無い点検役は空）。
    `cover` … カバーの点検役（コード・伴奏）。受け持ちは `COVER_SCOPE`。"""
    import song_gate_brief as gb                           # noqa: E402（循環を避けてここで）
    key = gate_key(gate, cover)
    if key not in GATE_FACTS:
        return ""
    if cover:
        steps = COVER_SCOPE.get(gate, ())
        lead = _GUARANTEE
    elif gb.is_second_tier(gate):
        steps = tuple(s for s in _ALL_STEPS if s in FORM_STEPS[form])
        lead = _GUARANTEE.replace("（見直さなくてかまいません）", "（全工程・見直さなくてかまいません）")
    else:
        steps = gb.scope_steps(gate, form)
        if not steps:
            return ""
        lead = _GUARANTEE
        if steps[0] != _ALL_STEPS[0]:
            lead += "\n  （受け持ちより前の工程も、それぞれ同じように形式の検査を通っています）"
    lines = [_HEAD, lead] + [_step_line(s, cover) for s in steps]
    lines.append("② 機械が数えて材料に出した事実（判断の材料です。良し悪しは機械が決めていません）:")
    lines += [f"  ・{t}" for t in items(GATE_FACTS[key], form)]
    lines.append("③ 機械が見ていないこと（あなたが読んで判断する所です）:")
    lines += [f"  ・{t}" for t in items(GATE_UNCHECKED[key], form)]
    return "\n".join(lines)


def checks_brief(gate: str, song=None) -> str:
    """呼び出し口（`song_gate.judge`）が使う: いま作っている曲（`song` を省くと `song_context.CURRENT_SONG`）の形で組む。
    曲が無ければ空（形が分からない）。カバーの曲はカバーの点検役の分。"""
    import song_gate_brief as gb                           # noqa: E402
    song = gb.current_song() if song is None else song
    if song is None:
        return ""
    form = getattr(song, "form", "song") or "song"
    if form not in FORM_STEPS:
        form = "song"
    return checks_text(gate, form, cover=gb.is_cover(song))
